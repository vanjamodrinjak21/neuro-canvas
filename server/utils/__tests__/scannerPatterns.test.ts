import { describe, it, expect } from 'vitest'
import { isScannerPath } from '../scannerPatterns'

describe('isScannerPath', () => {
  it.each([
    '/.env',
    '/.env.local',
    '/.env.production',
    '/.env.old',
    '/.env.backup',
    '/.env.example',
    '/api/.env',
    '/admin/.env',
    '/backend/.env',
    '/public/.env',
    '/app/.env',
    '/.ssh/id_rsa',
    '/.ssh/id_ed25519',
    '/.aws/credentials',
    '/.docker/config.json',
    '/.git/config',
    '/.npmrc',
    '/.pypirc',
    '/wp-admin/install.php',
    '/wp-login.php',
    '//wp-includes/wlwmanifest.xml',
    '//blog/wp-includes/wlwmanifest.xml',
    '//xmlrpc.php',
    '/credentials.json',
    '/secrets.json',
    '/secrets.yml',
    '/config/secrets.yml',
    '/service-account.json',
    '/gcp-credentials.json',
    '/google-credentials.json',
    '/firebase-config.json',
    '/__/firebase/init.json',
    '/key.json',
    '/keys/service-account.json',
    '/application.properties',
    '/application.yml',
    '/config/application.properties',
    '/settings.py',
    '/storage/logs/laravel.log',
    '/sa.json',
    '/config.env',
    '/config.json',
    '/config.js',
    '/env.json',
    '/env.js',
    '/__env.js',
    '/runtime-config.js',
    '/app-config.json',
    '/settings.json',
    '/openapi.json',
    '/swagger.json',
    '/api/env',
    '/api/config',
    '/api/settings',
    '/api/v1/env',
    '/api/v1/config',
    '/api/v1/settings',
    '/api/v2/config',
    '/api/v2/settings',
  ])('blocks scanner path %s', (path) => {
    expect(isScannerPath(path)).toBe(true)
  })

  it.each([
    '/',
    '/dashboard',
    '/map/abc123',
    '/templates',
    '/templates/awesome-template',
    '/docs',
    '/docs/getting-started/introduction',
    '/download',
    '/install',
    '/terms',
    '/privacy',
    '/robots.txt',
    '/sitemap.txt',
    '/sitemap_index.xml',
    '/atom.xml',
    '/manifest.webmanifest',
    '/health',
    '/api/health',
    '/api/account',
    '/api/auth/session',
    '/api/sync/stream',
    '/_nuxt/entry.Ab5q6xiI.css',
    '/_nuxt/CBImvxz-.js',
    '/.well-known/jwks.json',
  ])('does NOT block legitimate path %s', (path) => {
    expect(isScannerPath(path)).toBe(false)
  })

  it('returns false for empty input', () => {
    expect(isScannerPath('')).toBe(false)
  })
})
